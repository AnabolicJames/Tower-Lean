#!/usr/bin/env python3
"""Writes Tower/RV6/HankelDomF.lean: theta^k f (k <= 5) lies in the class HDom of HankelDom.lean.

The decompositions are those of tools/gen_besselL5.py (imported): each ldF_k is a sum of constant multiples of
products of one ITy factor (I0, t I1) and three KTy factors (K0, t K1); each thF_k is a sum of c t^m ldF_j.
The identity of each decomposition with the definition is re-checked here in exact arithmetic.
usage: python3 tools/gen_hankeldomf.py  (from the repository root)
"""
import os
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gen_besselL5 as G  # noqa: E402

ITYPE = {'u': 'ity_besselI0', 'p': 'ity_mul_besselI1'}
KTYPE = {'v': 'kty_besselK0', 'q': 'kty_mul_besselK1'}


def factor_lemma(ch):
    return ITYPE.get(ch) or KTYPE[ch]


def check():
    # each four-factor monomial has exactly one I-type factor, first
    for mons in G.LADDER['F']:
        for c, fs in mons:
            assert fs[0] in 'up' and all(ch in 'vq' for ch in fs[1:]), fs
    # the decompositions are the definitions (exact): reuse gen_besselL5's own checks
    G.check_ladder('F')
    for k in range(5):
        G.chain_cert(k)
    G.check_L5()


def ld_section():
    L = []
    for k, mons in enumerate(G.LADDER['F']):
        L.append('theorem hdom_ldF%d : HDom ldF%d := by' % (k, k))
        for i, (c, fs) in enumerate(mons):
            L.append('  have m%d := hdom_const_mul (%d : ℝ)' % (i + 1, c))
            L.append('    (hdom_prod4 %s)' % ' '.join(factor_lemma(ch) for ch in fs))
        expr = 'm1'
        for i in range(1, len(mons)):
            expr = 'hdom_add (%s) m%d' % (expr, i + 1) if i > 1 else 'hdom_add m1 m2'
        L.append('  have h0 := %s' % expr)
        L.append('  have hfun : ldF%d = fun x : ℝ =>' % k)
        L += G.wrap('      ', ['%s * (%s)' % (G.coef(c), G.mon_prod(fs, 'x')) for c, fs in mons], 8, tail=' := by')
        L.append('    funext x')
        L.append('    unfold ldF%d' % k)
        L.append('    ring')
        L.append('  rw [hfun]')
        L.append('  exact h0')
        L.append('')
    return L


def th_section():
    L = []
    for k in range(6):
        L.append('theorem hdom_thF%d : HDom thF%d := by' % (k, k))
        if G.single(k):
            j = G.TPOW[k][0][2]
            L.append('  have hfun : thF%d = ldF%d := rfl' % (k, j))
            L.append('  rw [hfun]')
            L.append('  exact hdom_ldF%d' % j)
            L.append('')
            continue
        for i, (co, m, j) in enumerate(G.TPOW[k]):
            if m == 0:
                L.append('  have m%d := hdom_const_mul (%d : ℝ) hdom_ldF%d' % (i + 1, co, j))
            else:
                L.append('  have m%d := hdom_const_mul (%d : ℝ) (hdom_pow_mul %d hdom_ldF%d)' % (i + 1, co, m, j))
        n = len(G.TPOW[k])
        expr = 'm1'
        for i in range(1, n):
            expr = 'hdom_add (%s) m%d' % (expr, i + 1) if i > 1 else 'hdom_add m1 m2'
        L.append('  have h0 := %s' % expr)
        L.append('  have hfun : thF%d = fun x : ℝ =>' % k)
        L += G.wrap('      ', [G.tpow_term(co, m, j, 'F', 'x') for co, m, j in G.TPOW[k]], 8, tail=' := rfl')
        L.append('  rw [hfun]')
        L.append('  exact h0')
        L.append('')
    return L


HEADER = '''import Mathlib
import Tower.RV6.BesselL5
import Tower.RV6.HankelDom

/-!
# `θᵏ f` is in the class `HDom` (`k ≤ 5`)

`ldF0 … ldF4` (the ladder of `f = I₀ K₀³` in `BesselL5.lean`) are sums of constant multiples of
products of one factor `I₀` or `t I₁` (`ITy`) and three factors `K₀` or `t K₁` (`KTy`), so they lie
in `HDom` (`hdom_prod4`, `hdom_const_mul`, `hdom_add`).  The θ-powers `thF0 … thF5` are sums of
`c tᵐ ldF_j` (`hdom_pow_mul`).  So every integrand `tʲ θᵏf(t) g(t)` of the Hankel dual is integrable
on `(0, ∞)` and every boundary term `t² θᵏf(t) g(t)` vanishes at both ends.

Generated by `tools/gen_hankeldomf.py` from the decompositions of `tools/gen_besselL5.py`.
-/

namespace Tower.RV6

'''


def main():
    check()
    out = HEADER.split('\n')
    out += ld_section()
    out += th_section()
    out += ['end Tower.RV6', '']
    text = '\n'.join(out)
    path = os.path.join('Tower', 'RV6', 'HankelDomF.lean')
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(text)
    print('decompositions checked; wrote %s (%d lines)' % (path, text.count('\n')))


if __name__ == '__main__':
    main()
