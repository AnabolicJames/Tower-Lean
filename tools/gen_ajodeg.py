"""Generate Tower/RV6/AJODEG.lean: the dual equation of g under the J1 transform.

A_k = AJ (theta^k g).  R1 gives A_k' = -A_(k+1)/x; R2 on gQ1 = (theta+2)^2 g, gQ2 = (theta+2)^3 g and
gR = -theta^5 g / (4 t^2) and the linearity of AJ give

  rel := 64 [theta (theta+2)^3 (theta+4)](A) + 4 x^2 [theta (theta+2) P3(theta)](A) + x^4 A_5 = 0,

and uG := x^2 A_4 + 4 (5A_4 + 15A_3 + 18A_2 + 8A_1) + 64 x^-2 (A_4 + 6A_3 + 12A_2 + 8A_1) satisfies
x uG' - 2 uG = -rel / x^2 = 0, so uG = c x^2.

Every linear_combination coefficient is computed here with sympy and the identity is asserted before it is written.
"""
import sympy as sp

OUT = 'Tower/RV6/AJODEG.lean'
L = []


def w(s=''):
    L.append(s)


x, y = sp.symbols('x y')  # y stands for x^-1
a = sp.symbols('a0:6')
Q1a, Q1b, Q2a, Q2b, R1, R2, T1, T2, F = sp.symbols('Q1a Q1b Q2a Q2b R1 R2 T1 T2 F')

# ---- the relation and its coefficients -------------------------------------------------------
H = [('q1a', Q1a, 4 * a[1] + 4 * a[2] + a[3]),
     ('q1b', Q1b, 4 * a[2] + 4 * a[3] + a[4]),
     ('q2a', Q2a, 8 * a[1] + 12 * a[2] + 6 * a[3] + a[4]),
     ('q2b', Q2b, 8 * a[2] + 12 * a[3] + 6 * a[4] + a[5]),
     ('r1', R1, 16 * T1 - 8 * a[1] - 18 * a[2] - 15 * a[3] - 5 * a[4]),
     ('r2', R2, 16 * T2 - 8 * a[2] - 18 * a[3] - 15 * a[4] - 5 * a[5]),
     ('e1', Q1b + 2 * Q1a, -x ** 2 * T1),
     ('e2', Q2b + 2 * Q2a, -x ** 2 * T2),
     ('e3', R2 + 2 * R1, -x ** 2 * F),
     ('hF', F, -sp.Rational(1, 4) * a[5])]
REL = (64 * (a[5] + 10 * a[4] + 36 * a[3] + 56 * a[2] + 32 * a[1])
       + 4 * x ** 2 * (5 * a[5] + 25 * a[4] + 48 * a[3] + 44 * a[2] + 16 * a[1]) + x ** 4 * a[5])
th = sp.symbols('th')
assert sp.expand(64 * th * (th + 2) ** 3 * (th + 4) - (th ** 5 + 10 * th ** 4 + 36 * th ** 3 + 56 * th ** 2 + 32 * th) * 64) == 0
assert sp.expand(4 * th * (th + 2) * (5 * th ** 3 + 15 * th ** 2 + 18 * th + 8)
                 - 4 * (5 * th ** 5 + 25 * th ** 4 + 48 * th ** 3 + 44 * th ** 2 + 16 * th)) == 0
unk = []
cs = []
for i in range(len(H)):
    co = sp.symbols('c%d_0:5' % i)
    unk += co
    cs.append(sum(co[j] * x ** j for j in range(5)))
ex = sp.expand(REL - sum(cs[i] * (H[i][1] - H[i][2]) for i in range(len(H))))
P = sp.Poly(ex, Q1a, Q1b, Q2a, Q2b, R1, R2, T1, T2, F, *a, x)
sol = sp.solve(P.coeffs(), unk, dict=True)[0]
COEF = [sp.expand(c.subs(sol).subs({u: 0 for u in unk})) for c in cs]
assert sp.expand(REL - sum(COEF[i] * (H[i][1] - H[i][2]) for i in range(len(H)))) == 0

# ---- uG and the cofactor of x * x^-1 = 1 ----------------------------------------------------------
B = a[4] + 6 * a[3] + 12 * a[2] + 8 * a[1]
UG = x ** 2 * a[4] + 4 * (5 * a[4] + 15 * a[3] + 18 * a[2] + 8 * a[1]) + 64 * B * y ** 2
d = {k: -a[k + 1] * y for k in range(5)}  # A_k' as produced by R1: -(A_(k+1)) / x
dB = d[4] + 6 * d[3] + 12 * d[2] + 8 * d[1]
UGD = (2 * x * a[4] + x ** 2 * d[4]) + 4 * (5 * d[4] + 15 * d[3] + 18 * d[2] + 8 * d[1]) \
    + (64 * dB * x ** 2 - 64 * B * (2 * x)) * y ** 4
ODE = sp.expand(x * UGD - 2 * UG)
# check with y = 1/x: x uG' - 2 uG = -rel / x^2
assert sp.simplify(ODE.subs(y, 1 / x) + REL / x ** 2) == 0
diff = sp.expand(ODE - (-y ** 2) * REL)  # must vanish modulo x y - 1
QOD, r = sp.div(diff, x * y - 1, y)
assert sp.expand(r) == 0, r
assert sp.expand(diff - QOD * (x * y - 1)) == 0


def lean_ax(e):
    s = str(sp.expand(e))
    for k in range(6):
        s = s.replace('a%d' % k, 'AJ thG%d x' % k)
    s = s.replace('y', 'x⁻¹').replace('**', '^')
    return s


