#!/usr/bin/env python3
"""Writes Tower/RV6/HankelODEF.lean: L3' hjF = x^2 (c1 + c2 log x) on (0, inf).

uF = L3' hjF and wF = (vartheta - 2) uF in terms of A_k = hk thF_k x; their derivatives from hasDerivAt_hk_thF0..4;
x uF' - 2 uF = wF and x wF' - 2 wF = -(the relation of hk_relation_F) = 0; then two first-order equations.
Every linear_combination cofactor is computed and checked here in exact arithmetic (x^(-1) an independent variable).
usage: python3 tools/gen_hankelodef.py  (from the repository root)
"""
import os
from fractions import Fraction

U = {3: (-1, -20, -64), 2: (0, -60, -384), 1: (0, -72, -768), 0: (0, -32, -512)}
W = {4: (1, 20, 64), 3: (0, 100, 640), 2: (0, 192, 2304), 1: (0, 176, 3584), 0: (0, 64, 2048)}
R = {5: (1, 20, 64), 4: (0, 140, 896), 3: (0, 392, 4864), 2: (0, 560, 12800), 1: (0, 416, 16384), 0: (0, 128, 8192)}


# ---- exact check (polynomials in x, y = 1/x, A0..A5 as dicts of exponent tuples) ----
N = 8


def mono(e):
    return tuple(e)


def P(d):
    return {k: Fraction(v) for k, v in d.items() if v != 0}


def add(p, q):
    r = dict(p)
    for k, v in q.items():
        r[k] = r.get(k, 0) + v
    return {k: v for k, v in r.items() if v != 0}


def mul(p, q):
    r = {}
    for a, u in p.items():
        for b, v in q.items():
            k = tuple(i + j for i, j in zip(a, b))
            r[k] = r.get(k, 0) + u * v
    return {k: v for k, v in r.items() if v != 0}


def sc(p, c):
    return {k: v * c for k, v in p.items() if v * c != 0}


def var(i):
    e = [0] * N
    e[i] = 1
    return {tuple(e): Fraction(1)}


def const(c):
    return {(0,) * N: Fraction(c)} if c else {}


X, Y = var(0), var(1)
A = [var(2 + j) for j in range(6)]


def xp(n):
    r = const(1)
    for _ in range(n):
        r = mul(r, X)
    return r


def pol(c):
    a, b, d = c
    return add(add(sc(xp(4), a), sc(xp(2), b)), const(d))


def dpol(c):
    a, b, _ = c
    return add(sc(xp(3), 4 * a), sc(X, 2 * b))


def comb(C):
    s = {}
    for k, c in C.items():
        s = add(s, mul(pol(c), A[k]))
    return s


def deriv(C):
    s, cof = {}, {}
    for k, c in C.items():
        dA = sc(add(sc(A[k], 2), A[k + 1]), -1)
        s = add(s, add(mul(dpol(c), A[k]), mul(mul(pol(c), dA), Y)))
        cof = add(cof, mul(pol(c), dA))
    return s, cof


def check():
    Ud, cu = deriv(U)
    e1 = add(add(add(mul(X, Ud), sc(comb(U), -2)), sc(comb(W), -1)), sc(mul(cu, add(mul(X, Y), const(-1))), -1))
    assert e1 == {}, e1
    Wd, cw = deriv(W)
    e2 = add(add(add(mul(X, Wd), sc(comb(W), -2)), comb(R)), sc(mul(cw, add(mul(X, Y), const(-1))), -1))
    assert e2 == {}, e2
    return cu, cw


# ---- Lean text ----
def ctext(c):
    a, b, d = c
    return '(%s * x ^ 4 + %s * x ^ 2 + %s)' % tuple(('(%d)' % v if v < 0 else '%d' % v) for v in (a, b, d))


def cotext(c, var='x'):
    return ctext(c).replace('x', var)


def term(c, k, v='x'):
    return '%s * hk thF%d %s' % (cotext(c, v), k, v)


def dterm(c, k):
    a, b, _ = c
    da = '(%s * (4 * x ^ 3) + %s * (2 * x))' % (('(%d)' % a if a < 0 else '%d' % a), ('(%d)' % b if b < 0 else '%d' % b))
    return '%s * hk thF%d x + %s * (-(2 * hk thF%d x + hk thF%d x) / x)' % (da, k, ctext(c), k, k + 1)


def cof_text(C):
    parts = []
    for k, c in C.items():
        parts.append('%s * (-(2 * hk thF%d x + hk thF%d x))' % (ctext(c), k, k + 1))
    return ' + '.join(parts)


PREAMBLE = r'''import Mathlib
import Tower.RV6.HankelDeriv

/-!
# `L₃′ hjF = x² (c₁ + c₂ log x)` on `(0, ∞)`

With `A_k = hk(θᵏ f)(x)` and `ϑ A_k = -2A_k - A_{k+1}` (`hasDerivAt_hk_thF0 … 4`):

* `uF = -(x⁴ + 20x² + 64) A₃ - (60x² + 384) A₂ - (72x² + 768) A₁ - (32x² + 512) A₀`, which is `L₃′ hjF`
  (`L₃′` with `ϑ ↦ -(2 + S)`, `S A_k = A_{k+1}`);
* `wF = (ϑ - 2) uF = (x⁴ + 20x² + 64) A₄ + (100x² + 640) A₃ + (192x² + 2304) A₂ + (176x² + 3584) A₁
  + (64x² + 2048) A₀` (`uF_ode`), and `(ϑ - 2) wF = 0` (`wF_ode`, from `hk_relation_F`);
* `ode_theta_two`, `ode_theta_two_log`: `x g' = 2g` gives `g = c x²`; `x u' - 2u = c x²` gives
  `u = x² (d + c log x)`;
* **`uF_eq`**: `L₃′ hjF = x² (c₁ + c₂ log x)` on `(0, ∞)` for some constants `c₁`, `c₂`.

That `c₁ = c₂ = 0` is the next step (`x → 0+`).  Generated by `tools/gen_hankelodef.py`.
-/

namespace Tower.RV6

/-- A function with derivative `0` on `(0, ∞)` is constant there. -/
theorem eq_one_of_hasDerivAt_zero {φ : ℝ → ℝ} (hd : ∀ z : ℝ, 0 < z → HasDerivAt φ 0 z)
    {x : ℝ} (hx : 0 < x) : φ x = φ 1 := by
  rcases le_total x 1 with h | h
  · have hcont : ContinuousOn φ (Set.Icc x 1) := fun z hz =>
      (hd z (lt_of_lt_of_le hx hz.1)).continuousAt.continuousWithinAt
    have hderiv : ∀ z ∈ Set.Ico x 1, HasDerivWithinAt φ 0 (Set.Ici z) z := fun z hz =>
      (hd z (lt_of_lt_of_le hx hz.1)).hasDerivWithinAt
    exact (constant_of_has_deriv_right_zero hcont hderiv 1 ⟨h, le_rfl⟩).symm
  · have hcont : ContinuousOn φ (Set.Icc 1 x) := fun z hz =>
      (hd z (lt_of_lt_of_le one_pos hz.1)).continuousAt.continuousWithinAt
    have hderiv : ∀ z ∈ Set.Ico 1 x, HasDerivWithinAt φ 0 (Set.Ici z) z := fun z hz =>
      (hd z (lt_of_lt_of_le one_pos hz.1)).hasDerivWithinAt
    exact constant_of_has_deriv_right_zero hcont hderiv x ⟨h, le_rfl⟩

/-- `x g' - 2g = 0` on `(0, ∞)` gives `g = c x²`. -/
theorem ode_theta_two {g g' : ℝ → ℝ} (hg : ∀ x : ℝ, 0 < x → HasDerivAt g (g' x) x)
    (h : ∀ x : ℝ, 0 < x → x * g' x - 2 * g x = 0) :
    ∃ c : ℝ, ∀ x : ℝ, 0 < x → g x = c * x ^ 2 := by
  have hd : ∀ z : ℝ, 0 < z → HasDerivAt (fun y : ℝ => g y / y ^ 2) 0 z := by
    intro z hz
    have h0 := (hg z hz).div (hasDerivAt_sqx z) (pow_ne_zero 2 hz.ne')
    have h1 : HasDerivAt (fun y : ℝ => g y / y ^ 2)
        ((g' z * z ^ 2 - g z * (2 * z)) / (z ^ 2) ^ 2) z := h0
    refine h1.congr_deriv ?_
    have hn : g' z * z ^ 2 - g z * (2 * z) = 0 := by linear_combination z * h z hz
    rw [hn, zero_div]
  refine ⟨g 1 / 1 ^ 2, fun x hx => ?_⟩
  have e := eq_one_of_hasDerivAt_zero hd hx
  have e' : g x / x ^ 2 = g 1 / 1 ^ 2 := e
  rw [div_eq_iff (pow_ne_zero 2 hx.ne')] at e'
  exact e'

/-- `x u' - 2u = c x²` on `(0, ∞)` gives `u = x² (d + c log x)`. -/
theorem ode_theta_two_log {u u' : ℝ → ℝ} {c : ℝ} (hu : ∀ x : ℝ, 0 < x → HasDerivAt u (u' x) x)
    (h : ∀ x : ℝ, 0 < x → x * u' x - 2 * u x = c * x ^ 2) :
    ∃ d : ℝ, ∀ x : ℝ, 0 < x → u x = x ^ 2 * (d + c * Real.log x) := by
  have hd : ∀ z : ℝ, 0 < z →
      HasDerivAt (fun y : ℝ => u y / y ^ 2 - c * Real.log y) 0 z := by
    intro z hz
    have h0 := ((hu z hz).div (hasDerivAt_sqx z) (pow_ne_zero 2 hz.ne')).sub
      ((Real.hasDerivAt_log hz.ne').const_mul c)
    have h1 : HasDerivAt (fun y : ℝ => u y / y ^ 2 - c * Real.log y)
        ((u' z * z ^ 2 - u z * (2 * z)) / (z ^ 2) ^ 2 - c * z⁻¹) z := h0
    refine h1.congr_deriv ?_
    have hn : u' z * z ^ 2 - u z * (2 * z) = c * z ^ 3 := by linear_combination z * h z hz
    have hinv : z * z⁻¹ = 1 := mul_inv_cancel₀ hz.ne'
    have e : c * z ^ 3 / (z ^ 2) ^ 2 = c * z⁻¹ := by
      rw [div_eq_iff (pow_ne_zero 2 (pow_ne_zero 2 hz.ne'))]
      linear_combination (-(c * z ^ 3)) * hinv
    rw [hn, e, sub_self]
  refine ⟨u 1 / 1 ^ 2 - c * Real.log 1, fun x hx => ?_⟩
  have e := eq_one_of_hasDerivAt_zero hd hx
  have e' : u x / x ^ 2 - c * Real.log x = u 1 / 1 ^ 2 - c * Real.log 1 := e
  have e2 : u x / x ^ 2 = u 1 / 1 ^ 2 - c * Real.log 1 + c * Real.log x := by linarith
  rw [div_eq_iff (pow_ne_zero 2 hx.ne')] at e2
  rw [e2]
  ring

theorem hasDerivAt_quart (a b c x : ℝ) :
    HasDerivAt (fun y : ℝ => a * y ^ 4 + b * y ^ 2 + c) (a * (4 * x ^ 3) + b * (2 * x)) x := by
  have h := (((hasDerivAt_powfour x).const_mul a).add ((hasDerivAt_sqx x).const_mul b)).add_const c
  have h' : HasDerivAt (fun y : ℝ => a * y ^ 4 + b * y ^ 2 + c)
      (a * (4 * x ^ 3) + b * (2 * x)) x := h
  exact h'

'''


def main():
    cu, cw = check()
    L = PREAMBLE.split('\n')
    for name, C, doc in (('uF', U, '`L₃′ hjF` in terms of `A_k = hk(θᵏ f)`.'),
                         ('wF', W, '`(ϑ - 2) L₃′ hjF` in terms of `A_k`.')):
        L.append('/-- %s -/' % doc)
        L.append('noncomputable def %s (x : ℝ) : ℝ :=' % name)
        ts = [term(c, k) for k, c in C.items()]
        L.append('  ' + ts[0] + ' +')
        for t in ts[1:-1]:
            L.append('    ' + t + ' +')
        L.append('    ' + ts[-1])
        L.append('')
        L.append('noncomputable def d%s (x : ℝ) : ℝ :=' % name)
        ds = [dterm(c, k) for k, c in C.items()]
        L.append('  ' + ds[0] + ' +')
        for t in ds[1:-1]:
            L.append('    ' + t + ' +')
        L.append('    ' + ds[-1])
        L.append('')
        L.append('theorem hasDerivAt_%s {x : ℝ} (hx : 0 < x) : HasDerivAt %s (d%s x) x := by' % (name, name, name))
        ks = list(C.keys())
        for i, k in enumerate(ks):
            a, b, d = C[k]
            L.append('  have m%d := (hasDerivAt_quart (%d) (%d) (%d) x).mul (hasDerivAt_hk_thF%d hx)' % (i + 1, a, b, d, k))
        expr = 'm1'
        for i in range(1, len(ks)):
            expr = '(%s).add m%d' % (expr, i + 1) if i > 1 else 'm1.add m2'
        L.append('  have h := %s' % expr)
        L.append('  have hfun : %s = fun y : ℝ =>' % name)
        ts = [term(C[k], k, 'y') for k in ks]
        L.append('      ' + ts[0] + ' +')
        for t in ts[1:-1]:
            L.append('        ' + t + ' +')
        L.append('        ' + ts[-1] + ' := rfl')
        L.append('  rw [hfun]')
        L.append('  exact h')
        L.append('')
    L.append('/-- `(ϑ - 2) uF = wF`: `x uF\' - 2 uF = wF`. -/')
    L.append('theorem uF_ode {x : ℝ} (hx : 0 < x) : x * duF x - 2 * uF x = wF x := by')
    L.append('  have hinv : x * x⁻¹ = 1 := mul_inv_cancel₀ hx.ne\'')
    L.append('  unfold duF uF wF')
    L.append('  linear_combination (%s) * hinv' % cof_text(U))
    L.append('')
    L.append('/-- `(ϑ - 2) wF = 0` (it is minus the relation `hk_relation_F`). -/')
    L.append('theorem wF_ode {x : ℝ} (hx : 0 < x) : x * dwF x - 2 * wF x = 0 := by')
    L.append('  have hinv : x * x⁻¹ = 1 := mul_inv_cancel₀ hx.ne\'')
    L.append('  have hrel := hk_relation_F hx.le')
    L.append('  unfold dwF wF')
    L.append('  linear_combination (-1 : ℝ) * hrel + (%s) * hinv' % cof_text(W))
    L.append('')
    L.append('/-- **`L₃′ hjF = x² (c₁ + c₂ log x)`** on `(0, ∞)`. -/')
    L.append('theorem uF_eq : ∃ c1 c2 : ℝ, ∀ x : ℝ, 0 < x → uF x = x ^ 2 * (c1 + c2 * Real.log x) := by')
    L.append('  obtain ⟨c2, hc2⟩ := ode_theta_two (g := wF) (g\' := dwF) (fun x hx => hasDerivAt_wF hx)')
    L.append('    (fun x hx => wF_ode hx)')
    L.append('  obtain ⟨c1, hc1⟩ := ode_theta_two_log (u := uF) (u\' := duF) (c := c2)')
    L.append('    (fun x hx => hasDerivAt_uF hx) (fun x hx => by rw [uF_ode hx, hc2 x hx])')
    L.append('  exact ⟨c1, c2, hc1⟩')
    L.append('')
    L.append('end Tower.RV6')
    L.append('')
    text = '\n'.join(L)
    path = os.path.join('Tower', 'RV6', 'HankelODEF.lean')
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(text)
    print('cofactors checked; wrote %s (%d lines)' % (path, text.count('\n')))


if __name__ == '__main__':
    main()
