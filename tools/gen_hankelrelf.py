#!/usr/bin/env python3
"""Writes Tower/RV6/HankelRelF.lean: the linear relation among A_k(x) = hk thF_k x (k = 0..5) for x >= 0.

  (Ra_k)  A_(k+2) + 4 A_(k+1) + 4 A_k = -(x^2 B_k)                  k = 0..3   (hk_theta2 on thF_k)
  (Rb_k)  B_(k+2) + 8 B_(k+1) + 16 B_k = -(x^2 C_k)                 k = 0, 1   (hk_theta2 on t^2 thF_k)
  (L)     A_5 - 20 B_3 - 60 B_2 - 72 B_1 - 32 B_0 + 64 C_1 + 128 C_0 = 0      (hk of L5_thF)
with B_k = hk (t^2 thF_k), C_k = hk (t^4 thF_k).  The final relation is x^4 (L) + sum alpha_k (Ra_k) + sum beta_k (Rb_k); the cofactors are
computed and the combination verified here in exact arithmetic (polynomials in x and the symbols A, B, C).
usage: python3 tools/gen_hankelrelf.py  (from the repository root)
"""
import os
from fractions import Fraction

TARGET = {5: (1, 20, 64), 4: (0, 140, 896), 3: (0, 392, 4864), 2: (0, 560, 12800), 1: (0, 416, 16384), 0: (0, 128, 8192)}
L5TERMS = [(1, 'A', 5), (-20, 'B', 3), (-60, 'B', 2), (-72, 'B', 1), (-32, 'B', 0), (64, 'C', 1), (128, 'C', 0)]


# polynomials in x as dict exponent -> Fraction; linear forms as dict symbol -> poly
def padd(p, q):
    r = dict(p)
    for k, v in q.items():
        r[k] = r.get(k, 0) + v
    return {k: v for k, v in r.items() if v != 0}


def pmul(p, q):
    r = {}
    for a, u in p.items():
        for b, v in q.items():
            r[a + b] = r.get(a + b, 0) + u * v
    return {k: v for k, v in r.items() if v != 0}


def lf_add(a, b):
    r = {s: dict(p) for s, p in a.items()}
    for s, p in b.items():
        r[s] = padd(r.get(s, {}), p)
    return {s: p for s, p in r.items() if p}


def lf_scale(a, p):
    return {s: pmul(q, p) for s, q in a.items() if pmul(q, p)}


def X(e, c=1):
    return {e: Fraction(c)}


def eq_Ra(k):  # lhs - rhs
    return {'A%d' % (k + 2): X(0), 'A%d' % (k + 1): X(0, 4), 'A%d' % k: X(0, 4), 'B%d' % k: X(2)}


def eq_Rb(k):
    return {'B%d' % (k + 2): X(0), 'B%d' % (k + 1): X(0, 8), 'B%d' % k: X(0, 16), 'C%d' % k: X(2)}


def eq_L():
    return {'%s%d' % (s, j): X(0, c) for c, s, j in L5TERMS}


ALPHA = {3: {2: Fraction(20), 0: Fraction(64)}, 2: {2: Fraction(60), 0: Fraction(640)},
         1: {2: Fraction(72), 0: Fraction(2048)}, 0: {2: Fraction(32), 0: Fraction(2048)}}
BETA = {1: {2: Fraction(-64)}, 0: {2: Fraction(-128)}}


def check():
    comb = lf_scale(eq_L(), X(4))
    for k, a in ALPHA.items():
        comb = lf_add(comb, lf_scale(eq_Ra(k), a))
    for k, b in BETA.items():
        comb = lf_add(comb, lf_scale(eq_Rb(k), b))
    target = {}
    for k, (a, b, c) in TARGET.items():
        target['A%d' % k] = {e: Fraction(v) for e, v in ((4, a), (2, b), (0, c)) if v}
    assert comb == target, (comb, target)


def ptext(p):
    """a polynomial in x as Lean text"""
    parts = []
    for e in sorted(p, reverse=True):
        c = p[e]
        assert c.denominator == 1
        c = c.numerator
        mono = '' if e == 0 else ('x' if e == 1 else 'x ^ %d' % e)
        if mono == '':
            parts.append('%d' % c)
        elif c == 1:
            parts.append(mono)
        else:
            parts.append('%d * %s' % (c, mono))
    s = ' + '.join(parts)
    return s.replace('+ -', '- ')


def A(k):
    return 'hk thF%d x' % k


def B(k):
    return 'hk (fun t => t ^ 2 * thF%d t) x' % k


def C(k):
    return 'hk (fun t => t ^ 4 * thF%d t) x' % k


HEADER = '''import Mathlib
import Tower.RV6.BesselL5
import Tower.RV6.HankelDomF
import Tower.RV6.HankelIBP

/-!
# The linear relation among `hk(θᵏ f)` at fixed `x ≥ 0`

With `A_k = hk thF_k x`, `B_k = hk (t² thF_k) x`, `C_k = hk (t⁴ thF_k) x`:

* `hk_rel_a0 … hk_rel_a3`: `A_{k+2} + 4A_{k+1} + 4A_k = -x² B_k` (`hk_theta2` on the chain of `θᵏ f`);
* `hk_rel_b0`, `hk_rel_b1`: `B_{k+2} + 8B_{k+1} + 16B_k = -x² C_k` (`hk_theta2` on `t² θᵏ f`, since
  `(θ + 2)² t² = t² (θ + 4)²`);
* `hk_rel_L5`: `A₅ - 20B₃ - 60B₂ - 72B₁ - 32B₀ + 64C₁ + 128C₀ = 0` (`hk` of `L5_thF`);
* **`hk_relation_F`**: eliminating `B` and `C`,
  `(x⁴ + 20x² + 64) A₅ + (140x² + 896) A₄ + (392x² + 4864) A₃ + (560x² + 12800) A₂
    + (416x² + 16384) A₁ + (128x² + 8192) A₀ = 0`.

With `A_k = (-(ϑ + 2))ᵏ hjF` (the derivative in `x`, next) this is `-(ϑ - 2)² L₃′ hjF = 0`.
Generated by `tools/gen_hankelrelf.py`, which computes the cofactors of the last step and checks
them in exact arithmetic.
-/

namespace Tower.RV6

'''


def main():
    check()
    L = HEADER.split('\n')
    for k in range(5):
        L.append('theorem hchain_thF%d : HChain thF%d thF%d :=' % (k, k, k + 1))
        L.append('  ⟨hdom_thF%d, hdom_thF%d, fun _ ht => hasDerivAt_thF%d ht⟩' % (k, k + 1, k))
        L.append('')
    for k in range(4):
        L.append('theorem hk_rel_a%d {x : ℝ} (hx : 0 ≤ x) :' % k)
        L.append('    %s + 4 * %s + 4 * %s = -(x ^ 2 * %s) := by' % (A(k + 2), A(k + 1), A(k), B(k)))
        L.append('  have h : hk (fun t => thF%d t + 4 * thF%d t + 4 * thF%d t) x' % (k + 2, k + 1, k))
        L.append('      = -(x ^ 2 * hk (fun t => t ^ 2 * thF%d t) x) :=' % k)
        L.append('    hk_theta2 hchain_thF%d hchain_thF%d hx' % (k, k + 1))
        L.append('  rw [hk_add_cmul (hdom_add hdom_thF%d (hdom_const_mul 4 hdom_thF%d)) hdom_thF%d 4 hx,'
                 % (k + 2, k + 1, k))
        L.append('    hk_add_cmul hdom_thF%d hdom_thF%d 4 hx] at h' % (k + 2, k + 1))
        L.append('  exact h')
        L.append('')
    for k in range(2):
        a, b, c = k + 2, k + 1, k
        L.append('theorem hk_rel_b%d {x : ℝ} (hx : 0 ≤ x) :' % k)
        L.append('    %s + 8 * %s' % (B(a), B(b)))
        L.append('      + 16 * %s = -(x ^ 2 * %s) := by' % (B(c), C(c)))
        L.append('  have hc0 := hchain_tsq hchain_thF%d' % c)
        L.append('  have hc1 := hchain_tsq (hchain_add hchain_thF%d (hchain_const_mul 2 hchain_thF%d))' % (b, c))
        L.append('  have h : hk (fun t => t ^ 2 * (thF%d t + 2 * thF%d t + 2 * (thF%d t + 2 * thF%d t))' % (a, b, b, c))
        L.append('        + 4 * (t ^ 2 * (thF%d t + 2 * thF%d t)) + 4 * (t ^ 2 * thF%d t)) x' % (b, c, c))
        L.append('      = -(x ^ 2 * hk (fun t => t ^ 2 * (t ^ 2 * thF%d t)) x) := hk_theta2 hc0 hc1 hx' % c)
        L.append('  have e1 : hk (fun t => t ^ 2 * (thF%d t + 2 * thF%d t + 2 * (thF%d t + 2 * thF%d t))' % (a, b, b, c))
        L.append('        + 4 * (t ^ 2 * (thF%d t + 2 * thF%d t)) + 4 * (t ^ 2 * thF%d t)) x' % (b, c, c))
        L.append('      = hk (fun t => t ^ 2 * thF%d t + 8 * (t ^ 2 * thF%d t) + 16 * (t ^ 2 * thF%d t)) x :='
                 % (a, b, c))
        L.append('    hk_congr (fun t => by ring) x')
        L.append('  have e2 : hk (fun t => t ^ 2 * (t ^ 2 * thF%d t)) x = %s :=' % (c, C(c)))
        L.append('    hk_congr (fun t => by ring) x')
        L.append('  rw [e1, e2, hk_add_cmul (hdom_add (hdom_pow_mul 2 hdom_thF%d)' % a)
        L.append('      (hdom_const_mul 8 (hdom_pow_mul 2 hdom_thF%d))) (hdom_pow_mul 2 hdom_thF%d) 16 hx,' % (b, c))
        L.append('    hk_add_cmul (hdom_pow_mul 2 hdom_thF%d) (hdom_pow_mul 2 hdom_thF%d) 8 hx] at h' % (a, b))
        L.append('  exact h')
        L.append('')
    # (L)
    def body(c, s, j):
        f = {'A': 'thF%d t' % j, 'B': '(t ^ 2 * thF%d t)' % j, 'C': '(t ^ 4 * thF%d t)' % j}[s]
        return f if c == 1 else '(%d) * %s' % (c, f) if c < 0 else '%d * %s' % (c, f)

    def hdom(s, j):
        return {'A': 'hdom_thF%d' % j, 'B': '(hdom_pow_mul 2 hdom_thF%d)' % j, 'C': '(hdom_pow_mul 4 hdom_thF%d)' % j}[s]

    def val(s, j):
        return {'A': A(j), 'B': B(j), 'C': C(j)}[s]

    stmt = ' + '.join(('%s' % val(s, j)) if c == 1 else '(%d) * %s' % (c, val(s, j)) if c < 0 else '%d * %s' % (c, val(s, j))
                      for c, s, j in L5TERMS)
    lam = ' + '.join(body(c, s, j) for c, s, j in L5TERMS)
    L.append('theorem hk_rel_L5 {x : ℝ} (hx : 0 ≤ x) :')
    L.append('    ' + stmt.replace(' + ', '\n      + ', 6).replace('\n      + ', ' + ', 0) + ' = 0 := by')
    L.append('  have h0 : hk (fun t => %s) x' % lam)
    L.append('      = hk (fun _ => 0) x := hk_congr (fun t => by linear_combination L5_thF t) x')
    L.append('  rw [hk_zero] at h0')
    # prefix HDom proofs
    Q = [hdom(L5TERMS[0][1], L5TERMS[0][2])]
    for c, s, j in L5TERMS[1:]:
        Q.append('(hdom_add %s (hdom_const_mul (%d) %s))' % (Q[-1], c, hdom(s, j)))
    rws = []
    for i in range(len(L5TERMS) - 1, 0, -1):
        c, s, j = L5TERMS[i]
        rws.append('hk_add_cmul %s %s (%d) hx' % (Q[i - 1], hdom(s, j), c))
    L.append('  rw [' + rws[0] + ',')
    for r in rws[1:-1]:
        L.append('    ' + r + ',')
    L.append('    ' + rws[-1] + '] at h0')
    L.append('  exact h0')
    L.append('')
    # final
    terms = []
    for k in range(5, -1, -1):
        a, b, c = TARGET[k]
        terms.append('(%s) * %s' % (ptext({e: Fraction(v) for e, v in ((4, a), (2, b), (0, c)) if v}), A(k)))
    L.append('/-- **The relation among `hk(θᵏ f)`** at fixed `x ≥ 0` (`= -(ϑ - 2)² L₃′ hjF` once `ϑ` acts). -/')
    L.append('theorem hk_relation_F {x : ℝ} (hx : 0 ≤ x) :')
    L.append('    ' + terms[0] + ' + ' + terms[1])
    L.append('      + ' + terms[2] + ' + ' + terms[3])
    L.append('      + ' + terms[4] + ' + ' + terms[5] + ' = 0 := by')
    L.append('  have hL := hk_rel_L5 hx')
    for k in range(4):
        L.append('  have ha%d := hk_rel_a%d hx' % (k, k))
    for k in range(2):
        L.append('  have hb%d := hk_rel_b%d hx' % (k, k))
    cert = ['x ^ 4 * hL']
    for k in (3, 2, 1, 0):
        cert.append('(%s) * ha%d' % (ptext(ALPHA[k]), k))
    for k in (1, 0):
        cert.append('(%s) * hb%d' % (ptext(BETA[k]), k))
    L.append('  linear_combination ' + ' + '.join(cert[:3]))
    L.append('    + ' + ' + '.join(cert[3:6]))
    L.append('    + ' + ' + '.join(cert[6:]))
    L.append('')
    L.append('end Tower.RV6')
    L.append('')
    text = '\n'.join(L)
    path = os.path.join('Tower', 'RV6', 'HankelRelF.lean')
    with open(path, 'w', encoding='utf-8') as fh:
        fh.write(text)
    print('cofactors checked; wrote %s (%d lines)' % (path, text.count('\n')))


if __name__ == '__main__':
    main()
