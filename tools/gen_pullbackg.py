"""Generate Tower/RV6/PullbackG.lean: v0(xm y) / Zax y is a quadratic in y.

v_k(x) = -AJ(theta^(k+1) g)(x) / x^2, k = 0..3.  R1 gives v_k' = -(2 v_k + v_(k+1)) / x, and uGv, the operator of uF applied to the v_k,
equals uG = 0.  The pull-back block of PullbackF.lean (same operator, same derivative relation) is copied with A_k -> v_k.
The v_k certificates are computed here (exact division by x x^-1 - 1) and asserted before they are written.
"""
import re
import sympy as sp

SRC = 'Tower/RV6/PullbackF.lean'
OUT = 'Tower/RV6/PullbackG.lean'

x, xi = sp.symbols('x xi')
A = sp.symbols('A0:6')


def lean(e):
    s = str(sp.expand(e))
    for k in range(6):
        s = s.replace('A%d' % k, 'AJ thG%d x' % k)
    return s.replace('xi', 'x⁻¹').replace('**', '^')


L = []


def w(s=''):
    L.append(s)


w('import Mathlib')
w('import Tower.RV6.PullbackF')
w('import Tower.RV6.ZeroG')
w()
w('/-!')
w('# The pull-back for `g`: `v₀(x(y)) / Z(y)` is a quadratic in `y`')
w()
w('Generated by `tools/gen_pullbackg.py`.  `v_k(x) = -AJ(θ^{k+1} g)(x)/x²` (`vG0` … `vG3`):')
w()
w('* `hasDerivAt_vG0` … `vG2`: `v_k\' = -(2v_k + v_{k+1})/x` (R1), the relation of `hk(θᵏ f)` in `HankelDeriv.lean`;')
w('* `uGv`, the operator of `uF` applied to the `v_k`, equals `uG`, so `uGv = 0` (`uGv_zero`, from `uG_zero`);')
w('* the pull-back of `PullbackF.lean` with `A_k` replaced by `v_k`: `hG0 = v₀/Z`, `hG1`, `hG2`,')
w('  `D hG2 = -(π³/256) P Z uGv(x) = 0`, and **`vG0_xm_quad`**: `v₀(xm y) = (a + b y + c y²) Zax y` for `y > 0`.')
w('-/')
w()
w('namespace Tower.RV6')
w()
w('open Real')
w()
for k in range(4):
    w('/-- `v_%d = -AJ(θ^%d g)/x²`. -/' % (k, k + 1))
    w('noncomputable def vG%d (x : ℝ) : ℝ := -(AJ thG%d x) / x ^ 2' % (k, k + 1))
    w()
for k in range(3):
    # derivative produced by (hA.neg).div (hasDerivAt_sqx x): ((-(-(A_{k+2})/x)) * x^2 - (-(A_{k+1})) * (2 x)) / (x^2)^2
    a1, a2 = A[k + 1], A[k + 2]
    lhs = (-(-a2 * xi)) * x ** 2 - (-a1) * (2 * x)
    lhs = lhs * xi ** 4
    rhs = -(2 * (-a1 * xi ** 2) + (-a2 * xi ** 2)) * xi
    diff = sp.expand(lhs - rhs)
    q, r = sp.div(diff, x * xi - 1, xi)
    assert sp.expand(r) == 0 and sp.expand(diff - q * (x * xi - 1)) == 0
    w('theorem hasDerivAt_vG%d {x : ℝ} (hx : 0 < x) :' % k)
    w('    HasDerivAt vG%d (-(2 * vG%d x + vG%d x) / x) x := by' % (k, k, k + 1))
    w('  have hA := hasDerivAt_AJ_thG%d hx' % (k + 1))
    w('  have h : HasDerivAt (fun y : ℝ => -(AJ thG%d y) / y ^ 2)' % (k + 1))
    w('      ((-(-(AJ thG%d x) / x) * x ^ 2 - -(AJ thG%d x) * (2 * x)) / (x ^ 2) ^ 2) x :=' % (k + 2, k + 1))
    w('    (hA.neg).div (hasDerivAt_sqx x) (pow_ne_zero 2 hx.ne\')')
    w('  have h\' : HasDerivAt vG%d' % k)
    w('      ((-(-(AJ thG%d x) / x) * x ^ 2 - -(AJ thG%d x) * (2 * x)) / (x ^ 2) ^ 2) x := h' % (k + 2, k + 1))
    w('  refine h\'.congr_deriv ?_')
    w('  have hxi : x * x⁻¹ = 1 := mul_inv_cancel₀ hx.ne\'')
    w('  unfold vG%d vG%d' % (k, k + 1))
    w('  linear_combination (%s) * hxi' % lean(q))
    w()
# uGv and uGv = uG
v = [-A[k + 1] * xi ** 2 for k in range(4)]
UGV = ((-x ** 4 - 20 * x ** 2 - 64) * v[3] + (-60 * x ** 2 - 384) * v[2] + (-72 * x ** 2 - 768) * v[1]
       + (-32 * x ** 2 - 512) * v[0])
UG = (x ** 2 * A[4] + 4 * (5 * A[4] + 15 * A[3] + 18 * A[2] + 8 * A[1])
      + 64 * (A[4] + 6 * A[3] + 12 * A[2] + 8 * A[1]) * xi ** 2)
assert sp.simplify((UGV - UG).subs(xi, 1 / x)) == 0
diff = sp.expand(UGV - UG)
q2, r2 = sp.div(diff, x * xi - 1, xi)
assert sp.expand(r2) == 0 and sp.expand(diff - q2 * (x * xi - 1)) == 0
w('/-- The operator of `uF` on the `v_k`. -/')
w('noncomputable def uGv (x : ℝ) : ℝ :=')
w('  ((-1) * x ^ 4 + (-20) * x ^ 2 + (-64)) * vG3 x +')
w('    (0 * x ^ 4 + (-60) * x ^ 2 + (-384)) * vG2 x +')
w('    (0 * x ^ 4 + (-72) * x ^ 2 + (-768)) * vG1 x +')
w('    (0 * x ^ 4 + (-32) * x ^ 2 + (-512)) * vG0 x')
w()
w('theorem uGv_eq_uG {x : ℝ} (hx : 0 < x) : uGv x = uG x := by')
w('  have hxi : x * x⁻¹ = 1 := mul_inv_cancel₀ hx.ne\'')
w('  unfold uGv uG vG0 vG1 vG2 vG3')
w('  linear_combination (%s) * hxi' % lean(q2))
w()
w('theorem uGv_zero {x : ℝ} (hx : 0 < x) : uGv x = 0 := by')
w('  rw [uGv_eq_uG hx, uG_zero hx]')
w()
# the pull-back block of PullbackF
src = open(SRC).read()
i0 = src.index('/-- `D A_0 = (π/4) P (2 A_0 + A_1)`. -/')
i1 = src.index('/-- `g\' = g₁`, `g₁\' = g₂`, `g₂\' = 0` on `(0, ∞)` gives `g = a + b y + c y²`. -/')
block = src[i0:i1]
REN = [('hasDerivAt_hkxm_thF', 'hasDerivAt_vGxm'), ('hasDerivAt_hk_thF', 'hasDerivAt_vG'), ('hk thF', 'vG'),
       ('hasDerivAt_hF', 'hasDerivAt_hG'), ('hF0', 'hG0'), ('hF1', 'hG1'), ('hF2', 'hG2'), ('uF_zero', 'uGv_zero'), ('uF', 'uGv')]
gblock = block
for a_, b_ in REN:
    gblock = gblock.replace(a_, b_)
assert 'thF' not in gblock and 'hk ' not in gblock and 'hF' not in gblock, 'renaming incomplete'
L.append(gblock.rstrip('\n'))
w()
w()
w('/-- **`v₀(xm y) = (a + b y + c y²) Zax y`** for `y > 0`. -/')
w('theorem vG0_xm_quad : ∃ a b c : ℝ, ∀ y : ℝ, 0 < y →')
w('    vG0 (xm y) = (a + b * y + c * y ^ 2) * Zax y := by')
w('  obtain ⟨a, b, c, h⟩ := quad_of_third_deriv_zero (g := hG0) (g1 := hG1) (g2 := hG2)')
w('    (fun y hy => hasDerivAt_hG0 hy) (fun y hy => hasDerivAt_hG1 hy)')
w('    (fun y hy => hasDerivAt_hG2_zero hy)')
w('  refine ⟨a, b, c, fun y hy => ?_⟩')
w('  have e : vG0 (xm y) * (Zax y)⁻¹ = a + b * y + c * y ^ 2 := h y hy')
w('  have hz : Zax y * (Zax y)⁻¹ = 1 := mul_inv_cancel₀ (Zax_pos hy).ne\'')
w('  linear_combination (Zax y) * e + (-(vG0 (xm y))) * hz')
w()
w('end Tower.RV6')
open(OUT, 'w').write('\n'.join(L) + '\n')
print('wrote', OUT, len(L))
